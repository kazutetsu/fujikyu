function openForm(labelText, cell) {
  currentRow = cell.parentElement;
  document.getElementById('popupTitle').textContent = labelText;
  document.getElementById('popupDescription').textContent = descriptions[labelText] || "情報なし";
  document.getElementById('carNumber').value = currentRow.children[1].textContent === "未入力" ? "" : currentRow.children[1].textContent;
  document.getElementById('note').value = currentRow.children[2].textContent === "未入力" ? "" : currentRow.children[2].textContent;
  document.getElementById('formOverlay').style.display = 'flex';
}

function closeForm() {
  document.getElementById('formOverlay').style.display = 'none';
}

async function applyEdit() {
  if (!currentRow) return;

  const label = currentRow.children[0].textContent;
  const newCarNumber = document.getElementById('carNumber').value;
  const newNote = document.getElementById('note').value;

  currentRow.children[1].textContent = newCarNumber || "未入力";
  currentRow.children[2].textContent = newNote || "未入力";

  try {
    await fetch('/api/schedules', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        date: new Date().toISOString().split('T')[0],
        label,
        car_number: newCarNumber,
        note: newNote
      })
    });
  } catch (err) {
    console.error("保存エラー:", err);
  }

  closeForm();
}