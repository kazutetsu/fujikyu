// JST形式の日付を取得
function getTodayStrJST() {
  const now = new Date();
  const jst = new Date(now.getTime() + 9 * 60 * 60 * 1000);
  return jst.toISOString().split("T")[0];
}

// 土日 or 祝日判定
function isHoliday(dateStr) {
  const date = new Date(dateStr);
  return date.getDay() === 0 || date.getDay() === 6 || holidayMap.hasOwnProperty(dateStr);
}

function getCurrentSection(description) {
  const now = new Date();
  const minutesNow = now.getHours() * 60 + now.getMinutes();

  const lines = description.split("\n");
  for (let line of lines) {
    const match = line.match(/^(.+?)(\d{3,4})→(\d{3,4})(.+?)$/);
    if (!match) continue;

    let [, from, start, end, to] = match;

    if (start.length === 3) start = "0" + start;
    if (end.length === 3) end = "0" + end;

    const startMin = parseInt(start.slice(0, 2)) * 60 + parseInt(start.slice(2));
    const endMin = parseInt(end.slice(0, 2)) * 60 + parseInt(end.slice(2));

    if (startMin <= minutesNow && minutesNow <= endMin) {
      return `${from}${start.slice(0, 2)}:${start.slice(2)}ー${end.slice(0, 2)}:${end.slice(2)}${to}`;
    }
  }

  return "";
}

